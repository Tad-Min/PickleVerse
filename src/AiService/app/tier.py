import hashlib
import json
import math
import pickle
from pathlib import Path
import numpy as np
from .models import observed_timing

FEATURES = ["mean_abs_timing", "late_rate", "early_rate", "kitchen_rate", "momentum_rate", "target_rate", "recovery_rate", "input_error_rate"]
TIERS = {"beginner", "intermediate", "advanced"}
FEATURE_VERSION = "raw-input-v3"
MIN_OPPORTUNITIES = 20
MIN_CONFIDENCE = .65


def observed_input_error(shot):
    if shot.outcome in ("WrongInput", "LateServe"):
        return True
    if shot.rawReleasedAt is not None and shot.rawInputMask:
        return False
    return None


def features(request, assistance=None):
    # Model contexts must match mode and assistance; autogenerated aim is never human accuracy.
    observed = request.onboardingShots if request.useInitialTrainingEvidence else request.onboardingShots + request.shots
    unique = {s.shotId: s for s in observed}
    shots = [s for s in unique.values() if assistance is None or s.assisted == assistance][:3000]
    timings = [timing for s in shots if (timing := observed_timing(s)) is not None]
    volleys = [s for s in shots if s.volley is True and s.kitchen is not None]
    momentum = [s.momentum for s in shots if s.volley is True and s.momentum is not None]
    targets = [s.targetHit for s in shots if not s.engineAimed and s.targetHit is not None]
    recovery = [s.recovered for s in shots if s.recovered is not None]
    input_errors = [error for s in shots if (error := observed_input_error(s)) is not None]
    mean = lambda values: float(np.mean(values)) if values else float("nan")
    values = [mean([abs(t) for t in timings]), mean([t > .065 for t in timings]),
              mean([t < -.065 for t in timings]), mean([s.kitchen for s in volleys]),
              mean(momentum), mean(targets), mean(recovery), mean(input_errors)]
    eligible = sum(any(v is not None for v in (observed_timing(s), s.kitchen if s.volley else None,
                                              s.momentum if s.volley else None, s.targetHit if not s.engineAimed else None,
                                              s.recovered, observed_input_error(s))) for s in shots)
    return values, eligible


def approved_manifest(manifest):
    partitions = [set(manifest[key]) for key in ("trainPlayers", "calibrationPlayers", "testPlayers")]
    train, calibration, test = partitions
    if not all(partitions) or train & calibration or train & test or calibration & test:
        return False
    counts = manifest["holdoutPlayers"]
    score, baseline = manifest["macroF1"], manifest["majorityF1"]
    return (
        isinstance(manifest["version"], str) and bool(manifest["version"].strip())
        and manifest["featureVersion"] == FEATURE_VERSION and manifest["features"] == FEATURES
        and manifest["approved"] is True and manifest["realExpertData"] is True
        and manifest["labelSource"] == "expert" and manifest["mode"] == "training"
        and isinstance(manifest["assisted"], bool)
        and manifest["minimumConfidence"] == MIN_CONFIDENCE and manifest["minimumOpportunities"] == MIN_OPPORTUNITIES
        and set(counts) == TIERS and min(counts.values()) >= 10 and sum(counts.values()) == len(test)
        and math.isfinite(score) and math.isfinite(baseline) and .70 <= score <= 1 and 0 <= baseline <= 1
        and score >= baseline + .05
    )


class TierPredictor:
    def __init__(self, path, enabled):
        self.status, self.model, self.manifest = "disabled", None, None
        if not enabled:
            return
        self.status = "unavailable"
        try:
            model_path = Path(path)
            manifest = json.loads(model_path.with_suffix(".json").read_text(encoding="utf-8"))
            if not approved_manifest(manifest) or hashlib.sha256(model_path.read_bytes()).hexdigest() != manifest["sha256"]:
                return
            # Artifacts are locally trained/deployed by operators, never supplied through an API.
            import joblib
            self.model = joblib.load(model_path)
            self.manifest, self.status = manifest, "enabled"
        except (OSError, ValueError, KeyError, TypeError, ImportError, EOFError, pickle.UnpicklingError):
            return

    def predict(self, request):
        values, count = features(request, self.manifest.get("assisted") if self.manifest else None)
        result = dict(status="insufficient_data", opportunities=count, confidence=0, modelVersion=None, tier=None)
        if self.model is None:
            result["status"] = "model_disabled" if self.status == "disabled" else "model_unavailable"
            return result
        result["modelVersion"] = self.manifest["version"]
        if count < MIN_OPPORTUNITIES or request.mode != self.manifest["mode"]:
            return result
        try:
            probabilities = self.model.predict_proba([values])[0]
        except (ValueError, TypeError, AttributeError):
            result["status"] = "model_unavailable"
            return result
        if not np.isfinite(probabilities).all():
            result["status"] = "model_unavailable"
            return result
        index = int(np.argmax(probabilities))
        result["confidence"] = float(probabilities[index])
        if probabilities[index] >= MIN_CONFIDENCE:
            result.update(status="ready", tier=str(self.model.classes_[index]))
        return result
